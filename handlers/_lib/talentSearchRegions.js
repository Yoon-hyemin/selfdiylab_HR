export function normalizeRegion(name) {
  if (typeof name !== 'string') return null;
  const t = name.trim();
  if (!t) return null;
  if (Object.prototype.hasOwnProperty.call(TALENT_SEARCH_REGIONS, t)) return t;
  return REGION_ALIASES[t] || null;
}

export function regionAllLabel(region) {
  return region + '전체';
}
